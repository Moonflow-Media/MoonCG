import { isPlainObject, type Json } from '@mooncg/core';

/** What is known about one replicant: its JSON Schema, or failing that its default value. */
export interface ReplicantTypeSource {
  readonly schema?: unknown;
  readonly default?: Json | undefined;
}

/**
 * How many `$ref`s one schema may expand. References are inlined, so a schema whose
 * definitions refer to each other several times over would otherwise grow without bound.
 * Beyond the limit a reference becomes `unknown`.
 */
export const MAX_REFERENCE_EXPANSIONS = 500;

/**
 * Generates the content of a bundle's `mooncg-env.d.ts`. It adds the bundle's replicants to
 * the SDK's `ReplicantMap`, under their bare and their qualified name, so that
 * `mc.replicant('score')` is typed without a generic.
 */
export function generateTypes(
  bundle: string,
  replicants: Readonly<Record<string, ReplicantTypeSource>>,
): string {
  const members = Object.entries(replicants).flatMap(([name, source]) => [
    `    ${memberKey(name)}: ${replicantType(source).text};`,
    `    ${quote(`${bundle}:${name}`)}: ReplicantMap[${quote(name)}];`,
  ]);
  const body = members.length === 0 ? '{}' : `{\n${members.join('\n')}\n  }`;
  return [
    '// Generated by `mooncg types` from mooncg.json. Do not edit.',
    "import '@mooncg/sdk/client';",
    '',
    "declare module '@mooncg/sdk/client' {",
    `  interface ReplicantMap ${body}`,
    '}',
    '',
  ].join('\n');
}

function replicantType({ schema, default: fallback }: ReplicantTypeSource): Type {
  if (schema !== undefined) return printSchema(schema, newContext(schema), 2);
  // A replicant without a default starts as null and may hold anything later.
  return fallback === undefined || fallback === null ? UNKNOWN : printValue(fallback, 2);
}

/**
 * Turns a JSON Schema into a TypeScript type. Supported: `type` (also as a list), `properties`
 * with `required`, `additionalProperties`, `items`, tuples (`prefixItems`, or `items` as a
 * list, with members beyond `minItems` optional), `enum`, `const`, `anyOf`, `oneOf`, `allOf`
 * and `$ref` into the same document. Everything else, including recursive and external
 * references, becomes `unknown`; keywords that only constrain values (`minimum`, `pattern`,
 * `format` and so on) do not affect the type.
 */
export function schemaToType(schema: unknown): string {
  return printSchema(schema, newContext(schema), 0).text;
}

/** Infers a type from an example value, such as a replicant's default. */
export function valueToType(value: Json): string {
  return printValue(value, 0).text;
}

/**
 * A printed type. `compound` says that it is a union or intersection at its top level, which
 * is what decides whether it needs parentheses inside an array or another combination.
 * Keeping that as a fact, instead of looking for `|` in the text, is what makes string
 * literals such as `"<"` or `"a | b"` safe.
 */
interface Type {
  readonly text: string;
  readonly compound: boolean;
}

const simple = (text: string): Type => ({ text, compound: false });
const UNKNOWN = simple('unknown');

interface Context {
  readonly root: unknown;
  /** References being expanded, to stop at a recursive one. */
  readonly resolving: Set<string>;
  expansionsLeft: number;
}

const newContext = (root: unknown): Context => ({
  root,
  resolving: new Set(),
  expansionsLeft: MAX_REFERENCE_EXPANSIONS,
});

/** The text of a type where a union or intersection would be misread without parentheses. */
const operand = (type: Type): string => (type.compound ? `(${type.text})` : type.text);

function unionOf(types: readonly Type[]): Type {
  const distinct = [...new Map(types.map((type) => [type.text, type])).values()];
  if (distinct.length === 1) return distinct[0] as Type;
  // `&` binds tighter than `|`, so intersections need no parentheses inside a union.
  return { text: distinct.map((type) => type.text).join(' | '), compound: true };
}

function intersectionOf(types: readonly Type[]): Type {
  if (types.length === 1) return types[0] as Type;
  return { text: types.map(operand).join(' & '), compound: true };
}

function printSchema(schema: unknown, context: Context, depth: number): Type {
  if (schema === false) return simple('never');
  if (!isPlainObject(schema)) return UNKNOWN;
  if (typeof schema.$ref === 'string') return printReference(schema.$ref, context, depth);

  const print = (part: unknown) => printSchema(part, context, depth);
  const parts: Type[] = [];
  const own = printOwnShape(schema, context, depth);
  if (own !== undefined) parts.push(own);
  if (Array.isArray(schema.allOf)) parts.push(...schema.allOf.map(print));
  if (Array.isArray(schema.anyOf)) parts.push(unionOf(schema.anyOf.map(print)));
  if (Array.isArray(schema.oneOf)) parts.push(unionOf(schema.oneOf.map(print)));
  return parts.length === 0 ? UNKNOWN : intersectionOf(parts);
}

/** The type described by the schema's own keywords, without its combinators. */
function printOwnShape(
  schema: Record<string, unknown>,
  context: Context,
  depth: number,
): Type | undefined {
  if ('const' in schema) return printLiteral(schema.const, depth);
  if (Array.isArray(schema.enum)) {
    return unionOf(schema.enum.map((value) => printLiteral(value, depth)));
  }
  const types =
    typeof schema.type === 'string'
      ? [schema.type]
      : Array.isArray(schema.type)
        ? schema.type
        : 'properties' in schema || 'additionalProperties' in schema
          ? ['object']
          : 'items' in schema || 'prefixItems' in schema
            ? ['array']
            : undefined;
  return types && unionOf(types.map((type) => printTyped(type, schema, context, depth)));
}

function printTyped(
  type: unknown,
  schema: Record<string, unknown>,
  context: Context,
  depth: number,
): Type {
  switch (type) {
    case 'string':
    case 'boolean':
    case 'null':
      return simple(type);
    case 'number':
    case 'integer':
      return simple('number');
    case 'array':
      return printArray(schema, context, depth);
    case 'object':
      return printObject(schema, context, depth);
    default:
      return UNKNOWN;
  }
}

function printArray(schema: Record<string, unknown>, context: Context, depth: number): Type {
  const element = (item: unknown) => operand(printSchema(item, context, depth));
  // A tuple is `prefixItems` in draft 2020-12 and a list under `items` in draft-07.
  const isModernTuple = Array.isArray(schema.prefixItems);
  const tuple = isModernTuple ? schema.prefixItems : schema.items;
  if (!Array.isArray(tuple)) return simple(`${element(schema.items ?? true)}[]`);

  // JSON Schema accepts a shorter array unless `minItems` forbids it, so only that many
  // members are required. A `minItems` beyond the listed members cannot be expressed.
  const required = typeof schema.minItems === 'number' ? schema.minItems : 0;
  const members = tuple.map((item, index) => `${element(item)}${index < required ? '' : '?'}`);
  const rest = isModernTuple ? schema.items : schema.additionalItems;
  if (rest !== false) members.push(`...${element(rest ?? true)}[]`);
  return simple(`[${members.join(', ')}]`);
}

function printObject(schema: Record<string, unknown>, context: Context, depth: number): Type {
  const properties = isPlainObject(schema.properties) ? Object.entries(schema.properties) : [];
  const required = new Set(Array.isArray(schema.required) ? schema.required : []);
  const extra = schema.additionalProperties;
  if (properties.length === 0) {
    if (extra === false) return simple('Record<string, never>');
    const values = extra === undefined ? UNKNOWN : printSchema(extra, context, depth);
    return simple(`Record<string, ${values.text}>`);
  }
  const members = properties.map(([key, property]) => {
    const optional = required.has(key) ? '' : '?';
    return `${memberKey(key, '"')}${optional}: ${printSchema(property, context, depth + 1).text}`;
  });
  // TypeScript cannot say "these members, and any other key of type T", so extra keys are
  // typed loosely. Without `additionalProperties` the type is closed, to catch typos.
  if (extra !== undefined && extra !== false) members.push('[key: string]: unknown');
  return block(members, depth);
}

function printReference(reference: string, context: Context, depth: number): Type {
  if (!reference.startsWith('#/') || context.resolving.has(reference)) return UNKNOWN;
  if (context.expansionsLeft <= 0) return UNKNOWN;
  const target = resolvePointer(context.root, reference.slice(2));
  if (target === undefined) return UNKNOWN;

  context.expansionsLeft--;
  context.resolving.add(reference);
  const type = printSchema(target, context, depth);
  context.resolving.delete(reference);
  return type;
}

/** Follows a JSON Pointer given as a URI fragment, which may be percent-encoded. */
function resolvePointer(root: unknown, pointer: string): unknown {
  let target: unknown = root;
  for (const token of pointer.split('/')) {
    let key: string;
    try {
      key = decodeURIComponent(token).replaceAll('~1', '/').replaceAll('~0', '~');
    } catch {
      return undefined;
    }
    target = isPlainObject(target) && Object.hasOwn(target, key) ? target[key] : undefined;
  }
  return target;
}

function printLiteral(value: unknown, depth: number): Type {
  return typeof value === 'object' && value !== null
    ? printValue(value as Json, depth)
    : simple(JSON.stringify(value));
}

function printValue(value: Json, depth: number): Type {
  if (value === null) return simple('null');
  if (Array.isArray(value)) {
    if (value.length === 0) return simple('unknown[]');
    const elements = unionOf(value.map((item: Json) => printValue(item, depth)));
    return simple(`${operand(elements)}[]`);
  }
  if (isPlainObject(value)) {
    const entries = Object.entries(value);
    if (entries.length === 0) return simple('Record<string, unknown>');
    return block(
      entries.map(
        ([key, member]) => `${memberKey(key, '"')}: ${printValue(member as Json, depth + 1).text}`,
      ),
      depth,
    );
  }
  return simple(typeof value);
}

function block(members: readonly string[], depth: number): Type {
  const indent = '  '.repeat(depth);
  return simple(`{\n${members.map((member) => `${indent}  ${member};`).join('\n')}\n${indent}}`);
}

function memberKey(key: string, quoteChar: "'" | '"' = "'"): string {
  if (/^[A-Za-z_$][\w$]*$/.test(key)) return key;
  return quoteChar === '"' ? JSON.stringify(key) : quote(key);
}

function quote(text: string): string {
  return `'${text.replaceAll('\\', '\\\\').replaceAll("'", "\\'")}'`;
}
